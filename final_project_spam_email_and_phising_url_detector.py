def predict_spam_smart(subject, body, threshold=None):
    """
    Smart spam detection with false positive protection.
    Uses: Whitelist check → ML model → Threshold → Final verdict
    Returns: (display_message, spam_probability, alert_message)
    """
    if threshold is None:
        threshold = OPTIMAL_THRESHOLD

    alert_message = ""

    if not subject.strip() and not body.strip():
        return " ☢️ Please enter subject or body text.", 0.0, alert_message

    text = (subject + " " + body).strip()

    # Step 1: Whitelist check
    if check_whitelist(text):
        return ("✅ LEGITIMATE — Whitelisted Pattern\nThis email matches known legitimate patterns (order/receipt/meeting etc.)\nConfidence: 99%", 0.01, alert_message)

