"""
# ============================================================
# CELL 13 — Feature Engineering for Phishing URLs
# ============================================================
"""

def extract_url_features(url):
    """Extract structural features from URL for ML model"""
    try:
        parsed = urlparse(str(url))
        hostname = parsed.netloc
        path = parsed.path
        query = parsed.query

        features = {
            'url_length': len(str(url)),
            'hostname_length': len(hostname),
            'path_length': len(path),
            'num_dots': str(url).count('.'),
            'num_hyphens': str(url).count('-'),
            'num_slashes': str(url).count('/'),
            'num_at': str(url).count('@'),
            'num_question': str(url).count('?'),
            'num_equals': str(url).count('='),
            'num_ampersand': str(url).count('&'),
            'num_digits': sum(c.isdigit() for c in str(url)),
            'num_subdomains': len(hostname.split('.')) - 2 if hostname else 0,
            'has_https': 1 if str(url).startswith('https') else 0,
            'has_ip': 1 if re.match(r'^(?:[0-9]{1,3}\.){3}[0-9]{1,3}$', hostname) else 0,
            'has_at_symbol': 1 if '@' in str(url) else 0,
            'is_shortened': 1 if any(s in str(url) for s in ['bit.ly', 'goo.gl', 'tinyurl', 't.co', 'ow.ly']) else 0,
            'num_params': len(query.split('&')) if query else 0,
            'special_char_ratio': sum(not c.isalnum() for c in str(url)) / max(len(str(url)), 1),
            'digit_ratio': sum(c.isdigit() for c in str(url)) / max(len(str(url)), 1),
        }
        return features
    except:
        return {k: 0 for k in ['url_length', 'hostname_length', 'path_length', 'num_dots',
                                 'num_hyphens', 'num_slashes', 'num_at', 'num_question',
                                 'num_equals', 'num_ampersand', 'num_digits', 'num_subdomains',
                                 'has_https', 'has_ip', 'has_at_symbol', 'is_shortened',
                                 'num_params', 'special_char_ratio', 'digit_ratio']}

# Extract features from URL column
