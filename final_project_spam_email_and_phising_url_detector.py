"""# ============================================================
# CELL 5 — Clean & Preprocess Spam Dataset
# ============================================================

"""

# Fix text columns
text_columns = spam_df.select_dtypes(include='object').columns
for col in text_columns:
    spam_df[col] = spam_df[col].fillna('')

# Create combined text column
if 'subject' in spam_df.columns and 'body' in spam_df.columns:
    spam_df['text_combined'] = spam_df['subject'].astype(str) + ' ' + spam_df['body'].astype(str)
elif 'body' in spam_df.columns:
    spam_df['text_combined'] = spam_df['body'].astype(str)
else:
    text_cols = spam_df.select_dtypes(include='object').columns.tolist()
    spam_df['text_combined'] = spam_df[text_cols[0]].astype(str)

# Fix URLs column
if 'urls' in spam_df.columns:
    spam_df['urls'] = pd.to_numeric(spam_df['urls'], errors='coerce').fillna(0)

# Remove duplicates
before = spam_df.shape[0]
spam_df.drop_duplicates(inplace=True)
print(f"✅ Removed {before - spam_df.shape[0]} duplicate rows")
print(f"✅ Dataset shape after cleaning: {spam_df.shape}")

# Check label column
print(f"\nLabel distribution:\n{spam_df['label'].value_counts()}")

"""
# ============================================================
# CELL 6 — Text Preprocessing (Normalize, Tokenize, Lemmatize)
# ============================================================
"""

lemmatizer = WordNetLemmatizer()
stop_words = set(stopwords.words('english'))

def preprocess_text(text):
    """Full text preprocessing pipeline"""
    # Lowercase
    text = str(text).lower()
    # Remove numbers
    text = re.sub(r'\d+', '', text)
    # Remove special characters
    text = re.sub(r'[^\w\s]', '', text)
    # Remove extra whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    # Tokenize
    tokens = word_tokenize(text)
    # Remove stop words and lemmatize
    tokens = [lemmatizer.lemmatize(t) for t in tokens if t not in stop_words and len(t) > 2]
    return ' '.join(tokens)

print("Preprocessing text (this may take a few minutes)...")
spam_df['text_processed'] = spam_df['text_combined'].apply(preprocess_text)

# Remove zero-length messages
spam_df = spam_df[spam_df['text_processed'].str.len() > 0].reset_index(drop=True)
print(f"✅ Text preprocessing complete. Dataset shape: {spam_df.shape}")
print(f"\nSample processed text:\n{spam_df['text_processed'].iloc[0][:200]}")

"""
# ============================================================
# CELL 7 — TF-IDF Vectorization + Feature Engineering
# ============================================================
"""

# TF-IDF with bigrams for better context
tfidf_vectorizer = TfidfVectorizer(
    max_features=10000,
    ngram_range=(1, 2),   # unigrams + bigrams — better than (1,1)
    min_df=2,
    max_df=0.95,
    sublinear_tf=True     # log normalization
)

X_tfidf = tfidf_vectorizer.fit_transform(spam_df['text_processed'])

# Add numerical features
if 'urls' in spam_df.columns:
    spam_df['urls'] = pd.to_numeric(spam_df['urls'], errors='coerce').fillna(0)
    spam_df['urls_transformed'] = np.log1p(spam_df['urls'])
    spam_df['text_length'] = spam_df['text_processed'].apply(len)
    spam_df['text_length_transformed'] = np.log1p(spam_df['text_length'])
    numerical_features = spam_df[['urls_transformed', 'text_length_transformed']].values
    X_combined = hstack([X_tfidf, csr_matrix(numerical_features)])
else:
    spam_df['text_length'] = spam_df['text_processed'].apply(len)
    spam_df['text_length_transformed'] = np.log1p(spam_df['text_length'])
    numerical_features = spam_df[['text_length_transformed']].values
    X_combined = hstack([X_tfidf, csr_matrix(numerical_features)])

y_spam = spam_df['label']

# Train-test split
X_train, X_test, y_train, y_test = train_test_split(
    X_combined, y_spam, test_size=0.2, random_state=42, stratify=y_spam
)

print(f"✅ TF-IDF + Feature Matrix ready")
print(f"   X_train: {X_train.shape} | X_test: {X_test.shape}")
print(f"   Label distribution in train:\n{pd.Series(y_train).value_counts()}")

"""
# ============================================================
# CELL 8 — Train ALL Spam Detection Models
# ============================================================
"""

# --- Model 1: Multinomial Naive Bayes ---
print("Training Multinomial Naive Bayes...")
